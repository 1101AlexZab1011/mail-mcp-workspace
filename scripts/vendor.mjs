#!/usr/bin/env node
// Copies third-party browser assets from node_modules into the add-on, so the
// add-on works offline and ships exactly what it uses. Run after npm install.
import { cp, mkdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const from = (path) => join(root, "node_modules", path);
const to = (path) => join(root, "thunderbird-addon/vendor", path);

await rm(to("pdfjs"), { recursive: true, force: true });
await mkdir(to("pdfjs"), { recursive: true });
for (const file of ["build/pdf.min.mjs", "build/pdf.worker.min.mjs", "web/pdf_viewer.mjs", "web/pdf_viewer.css", "LICENSE"]) {
  await cp(from(`pdfjs-dist/${file}`), to(`pdfjs/${file.split("/").pop()}`));
}
for (const dir of ["cmaps", "standard_fonts", "iccs", "web/images"]) {
  await cp(from(`pdfjs-dist/${dir}`), to(`pdfjs/${dir.split("/").pop()}`), { recursive: true });
}
// Image decoders only; the scripting engine (quickjs) stays out: PDF scripts never run here.
await mkdir(to("pdfjs/wasm"), { recursive: true });
for (const file of ["openjpeg.wasm", "jbig2.wasm", "qcms_bg.wasm", "openjpeg_nowasm_fallback.js", "jbig2_nowasm_fallback.js", "LICENSE_OPENJPEG", "LICENSE_JBIG2", "LICENSE_QCMS"]) {
  await cp(from(`pdfjs-dist/wasm/${file}`), to(`pdfjs/wasm/${file}`));
}
// xterm.js for the terminal panel.
await rm(to("xterm"), { recursive: true, force: true });
await mkdir(to("xterm"), { recursive: true });
for (const [file, name] of [["@xterm/xterm/lib/xterm.mjs", "xterm.mjs"], ["@xterm/xterm/css/xterm.css", "xterm.css"], ["@xterm/addon-fit/lib/addon-fit.mjs", "addon-fit.mjs"], ["@xterm/addon-web-links/lib/addon-web-links.mjs", "addon-web-links.mjs"], ["@xterm/xterm/LICENSE", "LICENSE"]]) {
  await cp(from(file), to(`xterm/${name}`));
}
// The Writer's editor (Milkdown + our Quarto layer), bundled into one module.
await rm(to("writer"), { recursive: true, force: true });
await mkdir(to("writer"), { recursive: true });
await build({
  entryPoints: [join(root, "src/writer/editor.mjs")],
  bundle: true, format: "esm", target: "firefox128", minify: true, legalComments: "linked",
  outfile: to("writer/writer.mjs"),
  logLevel: "warning",
});
for (const css of ["prosemirror.css", "tables.css", "gapcursor.css"]) await cp(from(`@milkdown/prose/lib/style/${css}`), to(`writer/${css}`));
// Slides: the deck model and agent ops (ours), and the editor app, built from the PPTist fork in
// slides/ (SLIDES_DIR overrides it; run `npm ci && npm run build-only` there first).
await mkdir(to("slides-core"), { recursive: true });
await build({
  entryPoints: [join(root, "src/slides/core.mjs")],
  bundle: true, format: "esm", target: "firefox128", minify: true,
  outfile: to("slides-core/slides-core.mjs"),
  logLevel: "warning",
});
// The shared page styles (shared/ui.css) use plain class names (.btn, .input, .menu) that the slide
// editor uses too. The Slides page gets them scoped to our own parts of the page.
const shared = await readFile(join(root, "thunderbird-addon/shared/ui.css"), "utf8");
const keyframes = shared.match(/@keyframes[^{]+\{[^{}]*\{[^}]*\}[^}]*\}/g) ?? [];
const rules = keyframes.reduce((css, block) => css.replace(block, ""), shared.replace(/@import[^;]+;/, ""));
// @scope does not style the scope's root element itself: the rules for our own containers (dialog
// backdrop, toast, the page menu) are repeated outside it, narrowed so the editor's .menu is untouched.
const rootRules = [...rules.matchAll(/(^|\n)(\.(?:dialog-backdrop|toast|menu)\b[^{]*)\{([^}]*)\}/g)]
  .filter(([, , selector]) => selector.split(",").every((part) => /^\s*\.(dialog-backdrop|toast|menu)\s*$/.test(part)))
  .map(([, , selector, body]) => `${selector.trim().replace(/\.menu$/, '.menu[role="menu"]')} {${body}}`);
await writeFile(to("slides-core/ui-scoped.css"), `/* Generated by scripts/vendor.mjs from shared/ui.css. Do not edit. */
@import url("../../shared/tokens.css");
${keyframes.join("\n")}
@scope (#start, #bar, .host-file, .host-actions, .dialog-backdrop, .toast, .menu[role="menu"]) {
${rules}
}
${rootRules.join("\n")}
`);
const slidesDist = join(process.env.SLIDES_DIR ?? join(root, "slides"), "dist");
if (await stat(join(slidesDist, "app.js")).catch(() => null)) {
  await rm(to("slides"), { recursive: true, force: true });
  await cp(slidesDist, to("slides"), { recursive: true, filter: (path) => !/\/(index\.html|favicon\.ico|logo\.png)$/.test(path) });
  await cp(join(slidesDist, "..", "LICENSE"), to("slides/LICENSE"));
} else console.warn(`No Slides build at ${slidesDist}; the Slides space keeps its previous copy`);
console.log("vendored pdf.js, xterm.js, the writer bundle and slides");
